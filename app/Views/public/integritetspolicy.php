        <h1>Integritetspolicy</h1>
    <p>
        Strängnäs Biredskap AB värnar om din personliga integritet. Här beskriver vi
        på ett enkelt sätt hur vi hanterar de personuppgifter du lämnar när du gör
        en förbokning eller beställning hos oss.
    </p>
    <p>
        Strängnäs Biredskap AB är personuppgiftsansvarig för de personuppgifter
        som samlas in via hemsidan.
    </p>

    <h2>Vilka uppgifter samlar vi in?</h2>
    <p>
        När du fyller i ett formulär för förbokning eller beställning samlar vi in
        ditt namn och din e-postadress.
    </p>
    <p>
        För att skydda formulären mot spam och missbruk kan vi även under en
        begränsad tid behandla en skyddad version av din IP-adress. Den används
        endast som en säkerhetsåtgärd och sparas i högst 24 timmar.
    </p>

    <h2>Varför använder vi dina uppgifter?</h2>
    <p>
        Vi använder dina uppgifter för att hantera din förbokning eller beställning
        och för att kunna kontakta dig i samband med den.
    </p>
    <p>
        Eftersom våra förbokningar normalt bara öppnar en eller ett par gånger per
        år kan vi även behålla din e-postadress mellan förbokningsperioderna.
        På så sätt kan vi kontakta dig när nästa förbokning öppnar, vilket gör att
        du inte behöver hålla reda på när det är dags att boka igen.
    </p>
    <p>
        Vi använder inte dina uppgifter för att skicka reklam eller nyhetsbrev
        som inte har samband med din förbokning.
    </p>

    <h2>Vilken är den rättsliga grunden?</h2>
    <p>
        Vi behandlar dina personuppgifter eftersom de behövs för att hantera den
        förbokning eller beställning du själv har bett oss om. För att kunna
        kontakta dig när nästa förbokningsperiod öppnar använder vi uppgifterna
        för det ändamål som du informerats om när du lämnade dina uppgifter.
    </p>
    <p>
        Du kan när som helst kontakta oss om du inte längre vill att vi behåller
        dina uppgifter för detta ändamål.
    </p>

    <h2>Vem får tillgång till dina uppgifter?</h2>
    <p>
        Vi säljer eller lämnar inte ut dina personuppgifter till andra företag
        för deras egna ändamål.
    </p>
    <p>
        Webbplatsen är hostad hos One.com. One.com behandlar personuppgifter
        för vår räkning i samband med drift och hosting av webbplatsen.
        Uppgifterna lagras på servrar inom EU, i Danmark.
    </p>

    <h2>Hur länge sparar vi uppgifterna?</h2>
    <p>
        Vi sparar dina uppgifter så länge de behövs för att hantera din
        förbokning eller beställning och för att kunna kontakta dig när nästa
        förbokningsperiod öppnar.
    </p>
    <p>
        När uppgifterna inte längre behövs för dessa ändamål raderas de.
        Du kan också när som helst be oss att radera dina uppgifter tidigare.
    </p>

    <h2>Hur skyddar vi dina uppgifter?</h2>
    <p>
        Vi vidtar lämpliga säkerhetsåtgärder för att skydda dina personuppgifter
        mot obehörig åtkomst, förlust eller annan otillåten användning.
    </p>

    <h2>Dina rättigheter</h2>
    <p>
        Du har rätt att få veta vilka personuppgifter vi har om dig och hur de
        används. Du kan också be oss att rätta felaktiga uppgifter eller radera
        uppgifter som vi inte längre behöver.
    </p>
    <p>
        I vissa situationer har du även rätt att begära att behandlingen av dina
        personuppgifter begränsas, att invända mot behandlingen eller att få ut
        dina personuppgifter i ett användbart format.
    </p>
    <p>
        Om du vill använda någon av dina rättigheter är du välkommen att kontakta
        oss på
        <a href="mailto:info@strangnas-biredskap.se">info@strangnas-biredskap.se</a>.
        Vi hjälper dig så snart som möjligt.
    </p>

    <h2>Vill du inte längre bli kontaktad?</h2>
    <p>
        Om du inte längre vill att vi sparar din e-postadress inför kommande
        förbokningar kan du enkelt kontakta oss och be oss radera dina uppgifter.
        Du behöver inte ange någon anledning.
    </p>

    <h2>Om du har synpunkter på hur vi hanterar dina uppgifter</h2>
    <p>
        Om du tycker att vi inte hanterar dina personuppgifter på rätt sätt kan
        du först kontakta oss så försöker vi hjälpa dig.
    </p>
    <p>
        Du har också rätt att lämna in ett klagomål till
        <a href="https://www.imy.se/" target="_blank" rel="noopener noreferrer">
            Integritetsskyddsmyndigheten (IMY)
        </a>,
        som är Sveriges tillsynsmyndighet för dataskydd.
    </p>

    <h2>Automatiserade beslut</h2>
    <p>
        Vi använder inte dina personuppgifter för automatiserade beslut eller
        profilering.
    </p>

